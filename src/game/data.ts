export function detectOptimalGraphics(): GraphicsSettings {
  const cores = typeof navigator !== 'undefined' ? navigator.hardwareConcurrency || 4 : 4;
  const isMobile = typeof window !== 'undefined' && window.innerWidth < 900;
  let presetKey: Exclude<GraphicsPresetId, 'custom'> = 'hd';
  if (isMobile && cores <= 4) presetKey = 'smooth';
  else if (isMobile) presetKey = 'balanced';
  else if (cores >= 8) presetKey = 'ultra';
  return {
    ...GRAPHICS_PRESETS[presetKey],
    weather: 'clear',
    timeOfDay: 'sunset',
  };
}

