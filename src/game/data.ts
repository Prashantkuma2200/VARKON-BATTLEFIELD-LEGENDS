export function computeEffectiveWeaponStats(
  weapon: WeaponDef,
  attachments: Partial<Record<AttachmentSlot, string>>,
  upgradeLevel = 1
) {
  let recoilMult = 1;
  let accuracyBonus = 0;
  let rangeBonus = 0;
  let magBonus = 0;
  let reloadMult = 1;
  let zoom = 1.25;
  let suppressed = false;

  Object.values(attachments).forEach((attId) => {
    const att = getAttachmentById(attId);
    if (!att) return;
    if (att.recoilMult) recoilMult *= att.recoilMult;
    if (att.accuracyBonus) accuracyBonus += att.accuracyBonus;
    if (att.rangeBonus) rangeBonus += att.rangeBonus;
    if (att.magBonus) magBonus += att.magBonus;
    if (att.reloadMult) reloadMult *= att.reloadMult;
    if (att.zoom) zoom = att.zoom;
    if (att.suppressed) suppressed = true;
  });

  // Subtle weapon mastery refinement (cosmetic/handling feel, fair balance)
  const lvBonus = Math.max(0, upgradeLevel - 1);

  return {
    damage: weapon.damage,
    fireRate: weapon.fireRate,
    range: Math.round(weapon.range + rangeBonus),
    accuracy: Math.min(100, Math.round(weapon.accuracy + accuracyBonus + lvBonus)),
    recoil: Math.max(8, Math.round(weapon.recoil * recoilMult - lvBonus)),
    magSize: weapon.magSize + magBonus,
    reloadTime: Number(Math.max(0.9, weapon.reloadTime * reloadMult - lvBonus * 0.04).toFixed(2)),
    zoom,
    suppressed,
  };
}
